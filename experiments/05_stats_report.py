"""Tasks 2.3-2.5 — per-suite statistics + tables from the main comparison.

Reads results/main_comparison/results.csv (produced by 04_main_comparison.py)
and emits, per FSSP-2 sub-suite (T, A, U):

  * aggregate quality: mean, SD, worst case of mu per solver (over instances;
    stochastic solvers first averaged over seeds per instance) — full
    precision, no "~1.0" (R3.m2); a residual (1 - mu) column for saturated
    values;
  * Friedman omnibus + pairwise Wilcoxon (Bonferroni-Holm) + Cliff's delta,
    all pairs, with honest magnitude labels (R4.2);
  * win/tie/loss pairwise table on seed-mean mu (task 2.5).

Outputs under results/main_comparison/analysis/:
  summary_by_suite.csv, stats_<suite>.json, wtl_<suite>.csv
LaTeX fragments under paper_fragments/:
  table_main_comparison.tex, table_stats_pairwise.tex, table_wtl.tex

Usage: .venv/bin/python experiments/05_stats_report.py
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from src.stats.analysis import analyze_suite, win_tie_loss

RESULTS = REPO / "results" / "main_comparison" / "results.csv"
OUT = REPO / "results" / "main_comparison" / "analysis"
FRAG = REPO / "paper_fragments"
SUITES = ["T", "A", "U"]

SOLVER_ORDER = ["fhga_fast", "fhga_thorough", "vanilla_ga", "random_search",
                "sim_anneal", "ils", "greedy_center", "alpha_cut",
                "dp_exact", "mitm", "cpsat"]


def load() -> pd.DataFrame:
    df = pd.read_csv(RESULTS)
    df = df[df["status"] == "ok"].copy()
    df["mu"] = df["mu"].astype(float)
    return df


def seed_mean_matrix(df: pd.DataFrame, suite: str):
    """matrix[solver][instance_id] = mean mu over seeds."""
    sub = df[df["suite"] == suite]
    matrix = defaultdict(dict)
    for (solver, iid), grp in sub.groupby(["solver", "instance_id"]):
        matrix[solver][iid] = float(grp["mu"].mean())
    return dict(matrix)


def aggregate_rows(df: pd.DataFrame):
    rows = []
    for suite in SUITES:
        sub = df[df["suite"] == suite]
        for solver, grp in sub.groupby("solver"):
            per_inst = grp.groupby("instance_id")["mu"].mean()
            worst_run = grp["mu"].min()
            rows.append({
                "suite": suite, "solver": solver,
                "n_instances": per_inst.size,
                "n_runs": len(grp),
                "mean_mu": per_inst.mean(),
                "sd_mu_across_instances": per_inst.std(ddof=1),
                "worst_instance_mean_mu": per_inst.min(),
                "worst_single_run_mu": worst_run,
                "mean_residual": 1.0 - per_inst.mean(),
                "mean_evals": grp["evals_used"].mean(),
                "mean_wall_time": grp["wall_time"].astype(float).mean(),
            })
    return pd.DataFrame(rows)


def latex_main_table(agg: pd.DataFrame) -> str:
    lines = [
        r"% Auto-generated by experiments/05_stats_report.py — do not edit by hand.",
        r"% Task 2.4 (R3.m2): full-precision per-suite quality table.",
        r"\begin{table}[t]", r"  \centering",
        r"  \caption{Membership quality per FSSP-2 sub-suite: mean, standard",
        r"  deviation across instances, and worst case (worst per-instance",
        r"  seed-mean and worst single run). Stochastic solvers: 20 seeds.}",
        r"  \label{tab:main-comparison}",
        r"  \begin{tabular}{llrrrr}", r"    \toprule",
        r"    Suite & Solver & mean $\mu$ & SD & worst inst. & worst run \\",
        r"    \midrule",
    ]
    for suite in SUITES:
        block = agg[agg["suite"] == suite]
        ordered = [s for s in SOLVER_ORDER if s in set(block["solver"])]
        for s in ordered:
            r = block[block["solver"] == s].iloc[0]
            name = s.replace("_", r"\_")
            lines.append(
                f"    {suite} & {name} & {r['mean_mu']:.6f} & "
                f"{r['sd_mu_across_instances']:.6f} & "
                f"{r['worst_instance_mean_mu']:.6f} & "
                f"{r['worst_single_run_mu']:.6f} \\\\")
        lines.append(r"    \midrule")
    lines[-1] = r"    \bottomrule"
    lines += [r"  \end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def latex_pairwise_table(all_stats: dict) -> str:
    lines = [
        r"% Auto-generated by experiments/05_stats_report.py — do not edit by hand.",
        r"% Task 2.3 (R4.2): FH-GA-Thorough vs each solver, per sub-suite.",
        r"% Effect sizes reported alongside p-values; interpret magnitudes,",
        r"% not stars.",
        r"\begin{table}[t]", r"  \centering",
        r"  \caption{Pairwise comparison of FH-GA-Thorough against every",
        r"  other solver per sub-suite: Wilcoxon signed-rank",
        r"  (Bonferroni--Holm adjusted, all pairs corrected together) and",
        r"  Cliff's $\delta$ with magnitude. Positive $\delta$ favours",
        r"  FH-GA-Thorough.}",
        r"  \label{tab:stats-pairwise}",
        r"  \begin{tabular}{llrrrl}", r"    \toprule",
        r"    Suite & vs.\ solver & $p_{\mathrm{Holm}}$ & $\delta$ &"
        r" med.\ $\Delta\mu$ & magnitude \\",
        r"    \midrule",
    ]
    for suite in SUITES:
        st = all_stats[suite]
        for pw in st["pairwise"]:
            a, b = pw["solver_a"], pw["solver_b"]
            if "fhga_thorough" not in (a, b):
                continue
            other = b if a == "fhga_thorough" else a
            sign = 1.0 if a == "fhga_thorough" else -1.0
            name = other.replace("_", r"\_")
            lines.append(
                f"    {suite} & {name} & {pw['p_holm']:.2e} & "
                f"{sign * pw['delta']:+.3f} & "
                f"{sign * pw['median_diff']:+.6f} & {pw['magnitude']} \\\\")
        lines.append(r"    \midrule")
    lines[-1] = r"    \bottomrule"
    lines += [r"  \end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def latex_wtl_table(wtl_by_suite: dict) -> str:
    lines = [
        r"% Auto-generated by experiments/05_stats_report.py — do not edit by hand.",
        r"% Task 2.5: win/tie/loss of FH-GA-Thorough vs each solver (seed-mean",
        r"% mu per instance, tolerance 1e-12).",
        r"\begin{table}[t]", r"  \centering",
        r"  \caption{Win/tie/loss counts of FH-GA-Thorough against each",
        r"  solver per sub-suite (per-instance seed-mean $\mu$).}",
        r"  \label{tab:wtl}",
        r"  \begin{tabular}{l" + "c" * len(SUITES) + "}", r"    \toprule",
        r"    vs.\ solver & " + " & ".join(f"Suite {s}" for s in SUITES)
        + r" \\", r"    \midrule",
    ]
    others = [s for s in SOLVER_ORDER if s != "fhga_thorough"]
    for other in others:
        cells = []
        for suite in SUITES:
            wtl = wtl_by_suite[suite].get(("fhga_thorough", other))
            cells.append("--" if wtl is None else f"{wtl[0]}/{wtl[1]}/{wtl[2]}")
        lines.append(f"    {other.replace('_', chr(92) + '_')} & "
                     + " & ".join(cells) + r" \\")
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def main() -> int:
    df = load()
    OUT.mkdir(parents=True, exist_ok=True)
    FRAG.mkdir(parents=True, exist_ok=True)

    agg = aggregate_rows(df)
    agg.to_csv(OUT / "summary_by_suite.csv", index=False)

    all_stats, wtl_by_suite = {}, {}
    for suite in SUITES:
        matrix = seed_mean_matrix(df, suite)
        res = analyze_suite(matrix)
        all_stats[suite] = {
            "friedman_chi2": res.friedman_chi2,
            "friedman_p": res.friedman_p,
            "n_instances": res.n_instances,
            "mean_ranks": res.mean_ranks,
            "pairwise": [pw.__dict__ for pw in res.pairwise],
        }
        with open(OUT / f"stats_{suite}.json", "w") as fh:
            json.dump(all_stats[suite], fh, indent=2)
        wtl = win_tie_loss(matrix)
        wtl_by_suite[suite] = wtl
        pd.DataFrame(
            [{"solver_a": a, "solver_b": b, "wins": w, "ties": t, "losses": l}
             for (a, b), (w, t, l) in sorted(wtl.items())]
        ).to_csv(OUT / f"wtl_{suite}.csv", index=False)
        print(f"suite {suite}: {res.n_instances} paired instances, "
              f"Friedman p={res.friedman_p:.3e}")

    (FRAG / "table_main_comparison.tex").write_text(latex_main_table(agg))
    (FRAG / "table_stats_pairwise.tex").write_text(
        latex_pairwise_table(all_stats))
    (FRAG / "table_wtl.tex").write_text(latex_wtl_table(wtl_by_suite))
    print("fragments written:", FRAG)
    return 0


if __name__ == "__main__":
    sys.exit(main())
