"""Tasks 4.1 + 4.2 — analysis of the crisp-objective and LS controls.

Joins results/controls/results.csv with the main comparison's fhga_fast /
fhga_thorough rows (same seeds, same protocol) and reports, per sub-suite:

  4.1  fhga_fast vs fhga_crisp_fast, fhga_thorough vs fhga_crisp_thorough:
       Wilcoxon (Holm within suite), Cliff's delta, mean/worst. This is the
       evidence base for DECISION 4.3 (fuzzy-vs-crisp positioning).
  4.2  fhga_fast (gradient LS) vs fhga_ls_bestflip vs fhga_ls_swap: same
       tests. If gradient LS shows no measurable advantage, the "gradient"
       claim is renamed/downgraded (R2.3) — the verdict lands in the
       fragment as data.

Outputs: results/controls/analysis/*.csv
Fragment: paper_fragments/table_controls.tex
Usage: .venv/bin/python experiments/12_controls_report.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats as sps

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from src.stats.analysis import (cliffs_delta, cliffs_magnitude,
                                holm_correction)

CONTROLS = REPO / "results" / "controls" / "results.csv"
MAIN = REPO / "results" / "main_comparison" / "results.csv"
OUT = REPO / "results" / "controls" / "analysis"
FRAG = REPO / "paper_fragments"
SUITES = ["T", "A", "U"]
PAIRS = [
    ("4.1", "fhga_fast", "fhga_crisp_fast"),
    ("4.1", "fhga_thorough", "fhga_crisp_thorough"),
    ("4.2", "fhga_fast", "fhga_ls_bestflip"),
    ("4.2", "fhga_fast", "fhga_ls_swap"),
]


def main() -> int:
    ctrl = pd.read_csv(CONTROLS)
    main_df = pd.read_csv(MAIN)
    main_df = main_df[(main_df["status"] == "ok")
                      & main_df["solver"].isin(["fhga_fast", "fhga_thorough"])]
    df = pd.concat([ctrl[ctrl["status"] == "ok"], main_df], ignore_index=True)
    df["mu"] = df["mu"].astype(float)

    seed_mean = (df.groupby(["suite", "solver", "instance_id"])["mu"]
                 .mean().reset_index())

    rows = []
    for suite in SUITES:
        sub = seed_mean[seed_mean["suite"] == suite]
        mats = {s: dict(zip(g["instance_id"], g["mu"]))
                for s, g in sub.groupby("solver")}
        raw_p, pending = [], []
        for task, a, b in PAIRS:
            if a not in mats or b not in mats:
                continue
            common = sorted(set(mats[a]) & set(mats[b]))
            xa = np.array([mats[a][i] for i in common])
            xb = np.array([mats[b][i] for i in common])
            d = xa - xb
            p = 1.0 if np.allclose(d, 0) else float(
                sps.wilcoxon(xa, xb, zero_method="wilcox").pvalue)
            raw_p.append(p)
            pending.append((task, a, b, xa, xb, d))
        for (task, a, b, xa, xb, d), p, ph in zip(pending, raw_p,
                                                  holm_correction(raw_p)):
            delta = cliffs_delta(xa, xb)
            rows.append({
                "task": task, "suite": suite, "solver": a, "control": b,
                "n_instances": len(d),
                "mean_a": xa.mean(), "mean_b": xb.mean(),
                "mean_diff": float(d.mean()),
                "median_diff": float(np.median(d)),
                "worst_a": xa.min(), "worst_b": xb.min(),
                "p_raw": p, "p_holm": ph,
                "cliffs_delta": delta,
                "magnitude": cliffs_magnitude(delta),
            })

    res = pd.DataFrame(rows)
    OUT.mkdir(parents=True, exist_ok=True)
    res.to_csv(OUT / "controls_tests.csv", index=False)

    lines = [
        r"% Auto-generated by experiments/12_controls_report.py — do not edit by hand.",
        r"% Tasks 4.1 (R4.1) and 4.2 (R2.3): control comparisons. Positive",
        r"% delta / diff favours the FH-GA arm over the control.",
        r"\begin{table}[t]", r"  \centering",
        r"  \caption{Control comparisons per sub-suite: the crisp-objective",
        r"  controls (identical operators, unclamped asymmetric-distance",
        r"  guidance) and the local-search controls (gradient LS replaced",
        r"  by best-improvement flips / swaps only). Wilcoxon signed-rank,",
        r"  Holm-adjusted within suite; Cliff's $\delta$ with magnitude.}",
        r"  \label{tab:controls}",
        r"  \begin{tabular}{lllrrrl}", r"    \toprule",
        r"    Suite & FH-GA arm & control & mean $\Delta\mu$ &"
        r" $p_{\mathrm{Holm}}$ & $\delta$ & magnitude \\",
        r"    \midrule",
    ]
    for suite in SUITES:
        for _, r in res[res["suite"] == suite].iterrows():
            a = r["solver"].replace("_", r"\_")
            b = r["control"].replace("_", r"\_")
            lines.append(
                f"    {suite} & {a} & {b} & {r['mean_diff']:+.6f} & "
                f"{r['p_holm']:.2e} & {r['cliffs_delta']:+.3f} & "
                f"{r['magnitude']} \\\\")
        lines.append(r"    \midrule")
    lines[-1] = r"    \bottomrule"
    lines += [r"  \end{tabular}", r"\end{table}", ""]
    (FRAG / "table_controls.tex").write_text("\n".join(lines))
    print(res.to_string(index=False))
    print("fragment written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
