"""Tasks 2.6 + 2.7 — coverage-corrected comparison and baseline-fairness tables.

Produces two LaTeX fragments plus a machine-readable summary:

  paper_fragments/table_coverage.tex
      Per-suite quality WITH a coverage column, and -- for Suite A, where
      dp_exact solves only 144 of 360 instances -- means restricted to the
      common-solved subset. The previously generated table compared
      dp_exact's mean over the instances it could solve against the
      heuristics' means over all instances, which is not a like-for-like
      comparison (R4.3).

  paper_fragments/table_baseline_fairness.tex
      sim_anneal and ils under mu guidance vs the shared crisp guide, with
      per-run zero-membership rates. Establishes that the baselines' large
      zero rates were an artefact of the flat mu plateau outside the
      support, not a quality result (R2.7, R4.3).

Usage: python3 experiments/19_fairness_coverage_report.py
"""

from __future__ import annotations

import collections
import csv
import json
import statistics as st
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from scipy.stats import wilcoxon  # noqa: E402

from src.stats.analysis import (cliffs_delta, cliffs_magnitude,  # noqa: E402
                                holm_correction)

FINAL = REPO / "results" / "final" / "combined.csv"
FAIR = REPO / "results" / "baseline_fairness" / "results.csv"
FRAG = REPO / "paper_fragments"
OUT_JSON = REPO / "results" / "baseline_fairness" / "summary.json"

# Solvers shown in the coverage table, in reporting order.
ORDER = ["dp_exact", "mitm", "cpsat", "flsss", "fhga_v2crisp", "fhga_v2",
         "fhga_fast", "fhga_thorough", "vanilla_ga", "random_search",
         "ils", "ils_crisp", "sim_anneal", "sim_anneal_crisp",
         "alpha_cut", "greedy_center"]
TEX = {"dp_exact": r"DP (exact)", "mitm": r"MITM (exact)",
       "cpsat": r"CP-SAT", "flsss": r"FLSSS", "fhga_v2crisp": r"FH-GA v2-crisp",
       "fhga_v2": r"FH-GA v2", "fhga_fast": r"FH-GA-Fast",
       "fhga_thorough": r"FH-GA-Thorough", "vanilla_ga": r"Vanilla GA",
       "random_search": r"Random search", "ils": r"ILS ($\mu$)",
       "ils_crisp": r"ILS (guided)", "sim_anneal": r"SA ($\mu$)",
       "sim_anneal_crisp": r"SA (guided)", "alpha_cut": r"$\alpha$-cut FPTAS",
       "greedy_center": r"Greedy"}


def load():
    runs = collections.defaultdict(list)     # (suite, solver, inst) -> [mu]
    allinst = collections.defaultdict(set)   # suite -> {inst}
    for path in (FINAL, FAIR):
        if not path.exists():
            continue
        with open(path) as fh:
            for r in csv.DictReader(fh):
                allinst[r["suite"]].add(r["instance_id"])
                if r["mu"] != "":
                    runs[(r["suite"], r["solver"], r["instance_id"])].append(
                        float(r["mu"]))
    return runs, allinst


def main() -> int:
    runs, allinst = load()
    solved = collections.defaultdict(set)
    for (s, sv, i) in runs:
        solved[(s, sv)].add(i)

    summary = {}
    lines = []
    for suite in ("T", "A", "U"):
        svs = [sv for sv in ORDER if (suite, sv) in solved]
        if not svs:
            continue
        n_all = len(allinst[suite])
        common = set.intersection(*[solved[(suite, sv)] for sv in svs])
        lines.append(r"    \midrule")
        lines.append(rf"    \multicolumn{{6}}{{l}}{{\textit{{Suite {suite}}} "
                     rf"({n_all} instances; {len(common)} solved by all "
                     rf"listed methods)}} \\")
        for sv in svs:
            own = sorted(solved[(suite, sv)])
            m_own = st.mean(st.mean(runs[(suite, sv, i)]) for i in own)
            m_com = st.mean(st.mean(runs[(suite, sv, i)]) for i in common)
            flat = [x for i in own for x in runs[(suite, sv, i)]]
            zero = 100.0 * sum(1 for x in flat if x == 0.0) / len(flat)
            cov = 100.0 * len(own) / n_all
            summary[f"{suite}/{sv}"] = {
                "coverage": len(own), "coverage_pct": cov,
                "mean_own": m_own, "mean_common": m_com, "zero_pct": zero,
                "runs": len(flat),
            }
            lines.append(
                rf"    {TEX.get(sv, sv)} & {cov:.0f}\% & {m_own:.6f} & "
                rf"{m_com:.6f} & {zero:.1f}\% & {len(flat)} \\")

    tbl = "\n".join([
        r"% Auto-generated by experiments/19_fairness_coverage_report.py.",
        r"% Task 2.7 (R4.3, R3.4): coverage-aware per-suite comparison.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \caption{Per-suite membership quality with solver coverage. "
        r"``Cov.'' is the percentage of the sub-suite on which the method "
        r"returns a subset at all; exact methods abstain where the "
        r"pseudo-polynomial table is infeasible. ``Mean (all)'' averages "
        r"over the instances each method solves, ``Mean (common)'' over the "
        r"subset solved by every listed method -- only the latter is a "
        r"like-for-like comparison. ``Zero'' is the fraction of runs whose "
        r"returned subset has membership exactly zero; on Suite U the "
        r"irreducible floor is the 8.1\% of instances whose true optimum is "
        r"itself zero. Stochastic solvers: 20 seeds.}",
        r"  \label{tab:coverage}",
        r"  \begin{tabular}{lrrrrr}",
        r"    \toprule",
        r"    Method & Cov. & Mean (all) & Mean (common) & Zero & Runs \\",
        *lines,
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table}",
        "",
    ])
    (FRAG / "table_coverage.tex").write_text(tbl)

    # ---- baseline fairness (Suite U, where both arms are complete) --------
    fair_lines, tests = [], []
    pairs = [("ils", "ils_crisp"), ("sim_anneal", "sim_anneal_crisp")]
    ctx = [("fhga_v2crisp", "ils_crisp"), ("fhga_v2crisp", "sim_anneal_crisp"),
           ("fhga_v2crisp", "random_search")]
    have = all(("U", sv) in solved for p in pairs for sv in p)
    if have:
        insts = sorted(solved[("U", "ils_crisp")])
        raw = []
        for a, b in pairs + ctx:
            x = [st.mean(runs[("U", a, i)]) for i in insts]
            y = [st.mean(runs[("U", b, i)]) for i in insts]
            try:
                raw.append(wilcoxon(x, y).pvalue)
            except ValueError:
                raw.append(1.0)
        adj = holm_correction(raw)
        for (a, b), p in zip(pairs + ctx, adj):
            x = [st.mean(runs[("U", a, i)]) for i in insts]
            y = [st.mean(runs[("U", b, i)]) for i in insts]
            d = cliffs_delta(y, x)
            tests.append({"baseline": a, "variant": b,
                          "delta_mean": st.mean(y) - st.mean(x),
                          "p_holm": p, "cliffs_delta": d,
                          "magnitude": cliffs_magnitude(d)})
            fair_lines.append(
                rf"    {TEX.get(b, b)} vs.\ {TEX.get(a, a)} & "
                rf"{st.mean(y) - st.mean(x):+.6f} & {p:.2e} & "
                rf"{d:+.3f} & {cliffs_magnitude(d)} \\")
        summary["U/tests"] = tests

    fair = "\n".join([
        r"% Auto-generated by experiments/19_fairness_coverage_report.py.",
        r"% Task 2.6 (R2.7, R4.3): guided-baseline fairness on Suite U.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \caption{Effect of steering the metaheuristic baselines by the "
        r"shared unclamped guide instead of the membership $\mu$ (Suite U, "
        r"384 instances, 20 seeds, identical budget and termination). "
        r"Because $\mu$ is flat at zero outside the support, $\mu$-steered "
        r"search stalls on a zero plateau; the guided arms are the ones used "
        r"in the baseline comparison. The last three rows place FH-GA "
        r"against the repaired baselines. Wilcoxon signed-rank over "
        r"per-instance seed means, Holm-adjusted.}",
        r"  \label{tab:baseline-fairness}",
        r"  \begin{tabular}{lrrrl}",
        r"    \toprule",
        r"    Comparison & $\Delta$ mean $\mu$ & $p_{\mathrm{Holm}}$ & "
        r"Cliff's $\delta$ & magnitude \\",
        r"    \midrule",
        *fair_lines,
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table}",
        "",
    ])
    (FRAG / "table_baseline_fairness.tex").write_text(fair)

    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(summary, indent=2))
    print(f"wrote {FRAG/'table_coverage.tex'}")
    print(f"wrote {FRAG/'table_baseline_fairness.tex'}")
    print(f"wrote {OUT_JSON}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
