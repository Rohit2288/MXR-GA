"""Tasks 5.1 + 5.2 — runtime table and the "fastest at large n" re-test.

From the fair-protocol main comparison CSV: per solver x suite, mean/median
wall-clock AND evals consumed (both logged for every run — R4.3, R2.9).
Task 5.2: at n in {500, 1000}, rank solvers by median wall-clock and by
median evals; the submitted paper's "fastest at large n" claim survives
only if FH-GA-Fast leads both views — the verdict is written into the
fragment as data, not prose spin.

Usage: .venv/bin/python experiments/11_runtime_report.py
Outputs: results/main_comparison/analysis/runtime_{by_suite,large_n}.csv
Fragment: paper_fragments/table_runtime.tex
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

RESULTS = REPO / "results" / "main_comparison" / "results.csv"
OUT = REPO / "results" / "main_comparison" / "analysis"
FRAG = REPO / "paper_fragments"
SUITES = ["T", "A", "U"]
SOLVER_ORDER = ["fhga_fast", "fhga_thorough", "vanilla_ga", "random_search",
                "sim_anneal", "ils", "greedy_center", "alpha_cut",
                "dp_exact", "mitm", "cpsat"]


def main() -> int:
    df = pd.read_csv(RESULTS)
    df = df[df["status"] == "ok"].copy()
    df["wall_time"] = df["wall_time"].astype(float)

    by_suite = df.groupby(["suite", "solver"]).agg(
        mean_wall=("wall_time", "mean"),
        median_wall=("wall_time", "median"),
        mean_evals=("evals_used", "mean"),
        median_evals=("evals_used", "median"),
        runs=("wall_time", "size"),
    ).reset_index()
    large = df[df["n"].isin([500, 1000])].groupby(["n", "solver"]).agg(
        median_wall=("wall_time", "median"),
        median_evals=("evals_used", "median"),
        runs=("wall_time", "size"),
    ).reset_index()

    OUT.mkdir(parents=True, exist_ok=True)
    by_suite.to_csv(OUT / "runtime_by_suite.csv", index=False)
    large.to_csv(OUT / "runtime_large_n.csv", index=False)

    lines = [
        r"% Auto-generated by experiments/11_runtime_report.py — do not edit by hand.",
        r"% Task 5.1 (R2.9, R4.3): runtime under the fair protocol.",
        r"\begin{table}[t]", r"  \centering",
        r"  \caption{Cost per run under the shared protocol: wall-clock",
        r"  seconds and evaluations consumed (median over runs), per",
        r"  sub-suite. Exact solvers consume one counted evaluation; their",
        r"  cost is wall-clock.}",
        r"  \label{tab:runtime}",
        r"  \begin{tabular}{llrrr}", r"    \toprule",
        r"    Suite & Solver & med.\ wall (s) & med.\ evals & runs \\",
        r"    \midrule",
    ]
    for suite in SUITES:
        block = by_suite[by_suite["suite"] == suite]
        for s in SOLVER_ORDER:
            r = block[block["solver"] == s]
            if r.empty:
                continue
            r = r.iloc[0]
            lines.append(
                f"    {suite} & {s.replace('_', chr(92) + '_')} & "
                f"{r['median_wall']:.3f} & {int(r['median_evals'])} & "
                f"{int(r['runs'])} \\\\")
        lines.append(r"    \midrule")
    lines[-1] = r"    \bottomrule"
    lines += [r"  \end{tabular}", r"\end{table}", "",
              r"% Task 5.2: large-n ranking (median wall-clock; then median"
              r" evals) —"]
    for n, sub in large.groupby("n"):
        rank_wall = sub.sort_values("median_wall")["solver"].tolist()
        rank_evals = sub.sort_values("median_evals")["solver"].tolist()
        lines.append(f"%   n={n}: by wall: {', '.join(rank_wall)}")
        lines.append(f"%   n={n}: by evals: {', '.join(rank_evals)}")
    verdict_wall = all(
        sub.sort_values("median_wall")["solver"].iloc[0] == "fhga_fast"
        for _, sub in large.groupby("n")) if len(large) else False
    lines.append(
        "%  'fastest at large n' claim "
        + ("SURVIVES on wall-clock" if verdict_wall else
           "does NOT survive on wall-clock — drop or reword the claim")
        + " (see rankings above; check evals view before wording).")
    lines.append("")
    (FRAG / "table_runtime.tex").write_text("\n".join(lines))
    print(by_suite.to_string(index=False))
    print("fragment written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
