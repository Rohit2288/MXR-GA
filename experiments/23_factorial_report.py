"""Task 2.10 analysis — main effects and interactions from the 2^5 design (R2.2).

Reviewer 2 asked why this exact combination of mechanisms is necessary. The
leave-one-out ablation cannot answer that: it is blind to interactions. This
script estimates, from the full 2^5 design:

  * main effect of each mechanism, as the mean change in mu when the
    mechanism is switched ON, averaged over all 16 settings of the other
    four (the standard factorial contrast);
  * all 10 two-way interactions, as half the difference between the effect
    of one factor when a second is ON and when it is OFF;
  * a paired Wilcoxon test per contrast over per-instance seed means, with
    Holm correction across the 15 contrasts, plus Cliff's delta.

A mechanism with a null main effect AND null interactions is inert in every
context tested, not merely on its own -- which is the rigorous form of the
claim the paper makes when it drops it.

Outputs:
  paper_fragments/table_factorial.tex
  results/factorial/effects.json

Usage: python3 experiments/23_factorial_report.py
"""

from __future__ import annotations

import collections
import csv
import itertools
import json
import statistics as st
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from scipy.stats import wilcoxon  # noqa: E402

from src.stats.analysis import (cliffs_delta, cliffs_magnitude,  # noqa: E402
                                holm_correction)

RES = REPO / "results" / "factorial" / "results.csv"
FRAG = REPO / "paper_fragments"
OUT = REPO / "results" / "factorial" / "effects.json"

FACTORS = ["init", "xover", "impact", "ls", "ctrl"]
LABEL = {"init": "Hybrid initialisation", "xover": "FB-UX crossover",
         "impact": "Impact-aware mutation", "ls": "Direction-guided LS",
         "ctrl": "Mamdani controller"}
SHORT = {"init": "init", "xover": "FB-UX", "impact": "impact",
         "ls": "LS", "ctrl": "ctrl"}


def main() -> int:
    # cell[(bits)][instance] = mean mu over seeds
    acc = collections.defaultdict(list)
    for r in csv.DictReader(open(RES)):
        if r["mu"] == "":
            continue
        bits = tuple(int(r[f]) for f in FACTORS)
        acc[(bits, r["instance_id"])].append(float(r["mu"]))
    cell = collections.defaultdict(dict)
    for (bits, inst), v in acc.items():
        cell[bits][inst] = st.mean(v)

    designs = list(itertools.product([0, 1], repeat=5))
    missing = [b for b in designs if b not in cell]
    if missing:
        print(f"WARNING: {len(missing)} configurations absent")
    insts = sorted(set.intersection(*[set(cell[b]) for b in cell]))
    print(f"{len(cell)} configurations x {len(insts)} instances")

    def paired(on_bits, off_bits):
        """Per-instance mean over the listed cells, ON minus OFF."""
        y = [st.mean(cell[b][i] for b in on_bits) for i in insts]
        x = [st.mean(cell[b][i] for b in off_bits) for i in insts]
        return x, y

    contrasts = []
    # Main effects.
    for k, f in enumerate(FACTORS):
        on = [b for b in designs if b[k] == 1]
        off = [b for b in designs if b[k] == 0]
        contrasts.append((LABEL[f], "main", on, off))
    # Two-way interactions: (effect of f1 | f2 on) - (effect of f1 | f2 off).
    for (k1, f1), (k2, f2) in itertools.combinations(enumerate(FACTORS), 2):
        on = [b for b in designs if b[k1] == b[k2]]        # both on / both off
        off = [b for b in designs if b[k1] != b[k2]]       # exactly one on
        contrasts.append((f"{SHORT[f1]} $\\times$ {SHORT[f2]}", "inter",
                          on, off))

    raw, rows_data = [], []
    for name, kind, on, off in contrasts:
        x, y = paired(on, off)
        try:
            p = wilcoxon(x, y).pvalue
        except ValueError:
            p = 1.0
        raw.append(p)
        rows_data.append((name, kind, x, y))
    adj = holm_correction(raw)

    lines_main, lines_int, js = [], [], []
    for (name, kind, x, y), p in zip(rows_data, adj):
        eff = st.mean(y) - st.mean(x)
        d = cliffs_delta(y, x)
        mag = cliffs_magnitude(d)
        row = (rf"    {name} & {eff:+.6f} & {p:.2e} & {d:+.3f} & {mag} \\")
        (lines_main if kind == "main" else lines_int).append(row)
        js.append({"contrast": name, "kind": kind, "effect": eff,
                   "p_holm": p, "cliffs_delta": d, "magnitude": mag})

    tbl = "\n".join([
        r"% Auto-generated by experiments/23_factorial_report.py.",
        r"% Task 2.10 (R2.2): full 2^5 factorial, main effects + interactions.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \caption{Full $2^{5}$ factorial over the five membership-aware "
        r"mechanisms (32 configurations, identical protocol, repair disabled "
        r"throughout). Each main effect is the mean change in $\mu$ when the "
        r"mechanism is enabled, averaged over all 16 settings of the other "
        r"four; each interaction is the difference between a factor's effect "
        r"with a second factor on and with it off. Wilcoxon signed-rank over "
        r"per-instance seed means, Holm-adjusted across all 15 contrasts. "
        r"Unlike a leave-one-out ablation, this design can distinguish a "
        r"mechanism that is inert in isolation from one that is inert in "
        r"every context.}",
        r"  \label{tab:factorial}",
        r"  \begin{tabular}{lrrrl}",
        r"    \toprule",
        r"    Contrast & effect on $\mu$ & $p_{\mathrm{Holm}}$ & "
        r"Cliff's $\delta$ & magnitude \\",
        r"    \midrule",
        r"    \multicolumn{5}{l}{\textit{Main effects}} \\",
        *lines_main,
        r"    \midrule",
        r"    \multicolumn{5}{l}{\textit{Two-way interactions}} \\",
        *lines_int,
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table}",
        "",
    ])
    (FRAG / "table_factorial.tex").write_text(tbl)

    # Best and worst configurations, for the text.
    ranked = sorted(((st.mean(cell[b][i] for i in insts), b) for b in cell),
                    reverse=True)
    names = lambda b: "+".join(f for f, v in zip(FACTORS, b) if v) or "none"
    summary = {
        "n_instances": len(insts), "n_configs": len(cell),
        "contrasts": js,
        "best_configs": [{"config": names(b), "mean_mu": m}
                         for m, b in ranked[:5]],
        "worst_configs": [{"config": names(b), "mean_mu": m}
                          for m, b in ranked[-3:]],
        "all_on": next(m for m, b in ranked if all(b)),
        "all_off": next(m for m, b in ranked if not any(b)),
    }
    OUT.write_text(json.dumps(summary, indent=2))

    print("\nMain effects:")
    for e in js:
        if e["kind"] == "main":
            print(f"  {e['contrast']:<26}{e['effect']:+.6f}  "
                  f"p={e['p_holm']:.2e}  d={e['cliffs_delta']:+.3f} "
                  f"({e['magnitude']})")
    print("\nSignificant interactions (p<0.05):")
    sig = [e for e in js if e["kind"] == "inter" and e["p_holm"] < 0.05]
    for e in sig or []:
        print(f"  {e['contrast']:<26}{e['effect']:+.6f}  "
              f"p={e['p_holm']:.2e}  d={e['cliffs_delta']:+.3f} "
              f"({e['magnitude']})")
    if not sig:
        print("  none")
    print(f"\nall five ON : {summary['all_on']:.6f}")
    print(f"all five OFF: {summary['all_off']:.6f}")
    print("top configurations:")
    for c in summary["best_configs"]:
        print(f"  {c['mean_mu']:.6f}  {c['config']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
